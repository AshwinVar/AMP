def sentence_digest(text) -> str:
    """16 hex characters of SHA-256(salt + normalize_text(text)): names a sentence without spelling it."""
    return hashlib.sha256((DECONTAMINATION_SALT + normalize_text(text)).encode("utf-8")).hexdigest()[:16]


# =========================================================================== validation and expansion
def _slot_values(family, name):
    if name in family.slots:
        return family.slots[name]
    if name in SHARED_SLOTS:
        return SHARED_SLOTS[name]
    raise CorpusError(f"family {family.family_id}: template slot {{{name}}} is not defined")


def _template_slots(template):
    names = []
    for name in _SLOT.findall(template):
        if name not in names:
            names.append(name)
    return names


def _combinations(family, template):
    total = 1
    for name in _template_slots(template):
        total *= len(_slot_values(family, name))
    return total


def validate_families(families=None, *, decontaminated=None) -> None:
    """Raise CorpusError unless every family is well formed and every label is covered.

    A family must keep MIN_FREE_PHRASINGS free phrasings AFTER decontamination.
    """
    families = FAMILIES if families is None else tuple(families)
    decontaminated = DECONTAMINATED if decontaminated is None else frozenset(decontaminated)
    seen_ids = set()
    per_label = {label: 0 for label in LABELS}
    for fam in families:
        if not isinstance(fam, Family):
            raise CorpusError(f"not a Family: {fam!r}")
        if not isinstance(fam.family_id, str) or not _FAMILY_ID.fullmatch(fam.family_id):
            raise CorpusError(f"family id {fam.family_id!r} must be lowercase letters, digits and '-'")
        if fam.family_id in seen_ids:
            raise CorpusError(f"duplicate family id {fam.family_id!r}")
        seen_ids.add(fam.family_id)
        if fam.label not in per_label:
            raise CorpusError(f"family {fam.family_id}: label {fam.label!r} is not in LABELS")
        per_label[fam.label] += 1
        if not fam.templates or not all(isinstance(t, str) and t.strip() for t in fam.templates):
            raise CorpusError(f"family {fam.family_id}: needs at least one non-empty template")
        if len(fam.free) < MIN_FREE_PHRASINGS or not all(isinstance(t, str) and normalize_text(t) for t in fam.free):
            raise CorpusError(f"family {fam.family_id}: needs at least {MIN_FREE_PHRASINGS} non-empty free phrasings")
        surviving = [t for t in fam.free if sentence_digest(t) not in decontaminated]
        if len(surviving) < MIN_FREE_PHRASINGS:
            raise CorpusError(f"family {fam.family_id}: only {len(surviving)} free phrasings survive "
                              f"decontamination (needs {MIN_FREE_PHRASINGS})")
        for name, values in fam.slots.items():
            if not isinstance(values, tuple) or not values or not all(isinstance(v, str) for v in values):
                raise CorpusError(f"family {fam.family_id}: slot {name!r} must be a non-empty tuple of strings")
        for template in fam.templates:
            count = _combinations(fam, template)
            if count > MAX_TEMPLATE_COMBINATIONS:
                raise CorpusError(f"family {fam.family_id}: template has {count} combinations "
                                  f"(> {MAX_TEMPLATE_COMBINATIONS})")
    thin = {label: n for label, n in per_label.items() if n < MIN_FAMILIES_PER_LABEL}
    if thin:
        raise CorpusError(f"labels with fewer than {MIN_FAMILIES_PER_LABEL} families: {thin}")


def _render(template, mapping):
    return " ".join(_SLOT.sub(lambda m: mapping[m.group(1)], template).split())


def candidate_sentences(family) -> list:
    """Every sentence the family could contribute before sampling and decontamination: free phrasings,
    then every rendering of every template (in template order)."""
    out = list(family.free)
    for template in family.templates:
        count = _combinations(family, template)
        if count > MAX_TEMPLATE_COMBINATIONS:
            raise CorpusError(f"family {family.family_id}: template has {count} combinations "
                              f"(> {MAX_TEMPLATE_COMBINATIONS})")
        names = _template_slots(template)
        for combo in itertools.product(*(_slot_values(family, name) for name in names)):
            out.append(_render(template, dict(zip(names, combo))))
    return out


def expand_family(family, *, seed, cap, decontaminated=None) -> list:
    """Free phrasings plus a seeded round-robin sample of template expansions, at most ``cap`` sentences.

    Decontaminated sentences are skipped (free phrasings included); the family fills from its other
    renderings.
    """
    if isinstance(cap, bool) or not isinstance(cap, int) or cap < len(family.free):
        raise CorpusError(f"family {family.family_id}: cap {cap!r} is smaller than its free phrasings")
    decontaminated = DECONTAMINATED if decontaminated is None else frozenset(decontaminated)
    rng = make_rng(seed, "corpus", family.family_id)
    per_template = []
    for template in family.templates:
        count = _combinations(family, template)
        if count > MAX_TEMPLATE_COMBINATIONS:
            raise CorpusError(f"family {family.family_id}: template has {count} combinations "
                              f"(> {MAX_TEMPLATE_COMBINATIONS})")
        names = _template_slots(template)
        rendered, keys = [], set()
        for combo in itertools.product(*(_slot_values(family, name) for name in names)):
            text = _render(template, dict(zip(names, combo)))
            key = normalize_text(text)
            if key and key not in keys:
                keys.add(key)
                rendered.append(text)
        rng.shuffle(rendered)
        per_template.append(rendered)

    out, seen = [], set()

    def add(text):
        key = normalize_text(text)
        if key and key not in seen and sentence_digest(key) not in decontaminated:
            seen.add(key)
            out.append(Example(text, family.label, family.family_id))

    for text in family.free:
        add(text)
    position = 0
    while len(out) < cap and any(position < len(r) for r in per_template):
        for rendered in per_template:
            if position < len(rendered) and len(out) < cap:
                add(rendered[position])
        position += 1
    return out


def build_corpus(*, seed=EXPANSION_SEED, cap=MAX_PER_FAMILY, families=None, decontaminated=None) -> list:
    """Every family expanded, in family order. A sentence already produced by an earlier family is
    dropped; a sentence claimed by two DIFFERENT labels is a CorpusError."""
    families = FAMILIES if families is None else tuple(families)
    decontaminated = DECONTAMINATED if decontaminated is None else frozenset(decontaminated)
    validate_families(families, decontaminated=decontaminated)
    owner = {}
    corpus = []
    for fam in families:
        for ex in expand_family(fam, seed=seed, cap=cap, decontaminated=decontaminated):
            key = normalize_text(ex.text)
            if key in owner:
                label, family_id = owner[key]
                if label != ex.label:
                    raise CorpusError(f"sentence claimed by {family_id} ({label}) and {fam.family_id} ({ex.label})")
                continue
            owner[key] = (ex.label, ex.family)
            corpus.append(ex)
    return corpus


def corpus_sha256(examples) -> str:
    """SHA-256 of the canonical JSON of (corpus version, [family, label, text] for every example)."""
    body = {"corpus_version": CORPUS_VERSION, "examples": [[e.family, e.label, e.text] for e in examples]}
    return hashlib.sha256(canonical_json(body)).hexdigest()


# =========================================================================== split
def split_corpus(examples, *, seed=SPLIT_SEED, test_frac=TEST_FRAC, val_frac=VAL_FRAC):
    """(train, val, test): whole families, split separately for each label so every label is in every split."""
    by_label = {}
    for ex in examples:
        by_label.setdefault(ex.label, []).append(ex)
    train, val, test = [], [], []
    for label in LABELS:
        items = by_label.get(label)
        if not items:
            raise CorpusError(f"no examples for label {label!r}")
        label_seed = make_rng(seed, "split", label).randrange(2 ** 31)
        tr, va, te = group_split(items, lambda e: e.family, test_frac=test_frac, val_frac=val_frac,
                                 seed=label_seed)
        train.extend(tr)
        val.extend(va)
        test.extend(te)
    return train, val, test


# =========================================================================== leakage
def char_ngrams(text, n=4) -> frozenset:
    """Character n-grams of ``" " + normalize_text(text) + " "``."""
    padded = f" {normalize_text(text)} "
    if len(padded) <= n:
        return frozenset([padded])
    return frozenset(padded[i:i + n] for i in range(len(padded) - n + 1))


def jaccard(a, b) -> float:
    union = len(a | b)
    return len(a & b) / union if union else 0.0


def leakage_report(corpus_texts, questions, *, threshold=LEAKAGE_JACCARD) -> dict:
    """Count corpus sentences that copy (exactly, or char-4-gram Jaccard >= threshold) an evaluation question.

    Returns counts and the INDICES of offending corpus sentences - never question text, so the
    corpus author can fix their own sentence without reading the evaluation set.
    """
    q_norm = sorted({normalize_text(q) for q in questions} - {""})
    if not q_norm:
        raise CorpusError("no evaluation questions to check against: a leakage check that loads nothing "
                          "would report all-clear")
    q_set = set(q_norm)
    q_grams = [(char_ngrams(q), q) for q in q_norm]
    exact, near, flagged = 0, 0, []
    checked = 0
    for index, text in enumerate(corpus_texts):
        key = normalize_text(text)
        checked += 1
        if key in q_set:
            exact += 1
            flagged.append(index)
            continue
        grams = char_ngrams(key)
        size = len(grams)
        for q_gram, _q in q_grams:
            other = len(q_gram)
            if min(size, other) < threshold * max(size, other):
                continue
            if jaccard(grams, q_gram) >= threshold:
                near += 1
                flagged.append(index)
                break
    return {"questions_checked": len(q_norm), "corpus_sentences_checked": checked, "exact": exact,
            "near": near, "threshold": threshold, "flagged_indices": flagged}
