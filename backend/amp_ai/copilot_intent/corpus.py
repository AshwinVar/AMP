"""The AMP-authored training corpus for the native copilot intent model.

WHAT THIS IS
------------
Every sentence the intent model learns from is written HERE, by AMP. No tenant
question is logged, stored or learned from - the model's consent basis is
"none required" precisely because of that. The corpus is organised in FAMILIES:
one family is one way of asking for one intent, written as

  * one or more TEMPLATES with ``{slot}`` placeholders, each slot a tuple of
    synonyms (family-local slots first, then ``SHARED_SLOTS``), and
  * at least three FREE phrasings written out in full: typos, terse forms,
    Indian-English and Hinglish shop-floor wording, the things templates miss.

``build_corpus`` expands every family with a seeded, round-robin sample of its
templates (at most ``MAX_PER_FAMILY`` sentences, free phrasings always kept).
``split_corpus`` then puts each WHOLE family in train, validation or test,
separately per label (70/15/15 of families), so no near-duplicate sentence can
sit on both sides of an evaluation.

AUTHORING PROTOCOL
------------------
1. Labels follow what each pillar in ``ai/assistant.py`` ANSWERS (read from the
   pillar functions' outputs), not which words its keyword table matches:

     help         what the copilot can do / how to use it
     trend        any comparison with an earlier period, "improving?", week on week
     inventory    stock, materials, reorder levels, stockouts, replenishment POs
     flow         work orders / jobs / WIP and the stage they are at
     shift        shift or crew attainment against target, best/worst shift
     delivery     customer (sales) orders, dispatch, on-time delivery, at-risk orders
     cost         the MONEY lost to downtime and scrap, costliest machine
     quality      first-pass yield, reject/fail rates, defects, inspections
     compliance   controlled documents, SOP reviews, approvals, audits, certificates
     maintenance  maintenance TASKS: open, overdue, PM schedule, approvals, calibration
     downtime     stoppage EVENTS over time: counts, causes, minutes lost, worst machine
     machines     the CURRENT state of machines: running, down, idle, in maintenance now
     production   output counts: units made, good units, runs, throughput, top producer
     oee          OEE and its availability/performance/quality factors, effectiveness
     briefing     "what needs attention", overall status, summaries, priorities
     __none__     small talk, off-topic, out-of-scope requests: the model has no opinion

2. The author did not open the three evaluation question files
   (test_ai_evaluation.py, test_ai_routing_holdout.py, test_ai_routing_holdout2.py)
   while writing this. That cannot be enforced, so ``leakage_report`` refuses any
   corpus sentence equal to, or with character 4-gram Jaccard >= 0.6 against, a
   question loaded from those files, and results are quoted as DIFFERENCES from
   the keyword router on the same questions.
   Disclosure: the author had read ``ai/assistant.py`` - including the keyword
   table ``_ROUTES`` - before writing this corpus. Labels were still assigned by
   intent, and no sentence was labelled or generated by running the router, but
   the corpus test split (which the author wrote) should be read as favourable to
   the model; the external question pool is the honest comparison.
3. No sentence starts with a find/locate prefix or names a specific machine: the
   router answers those BEFORE the model is consulted, so they are not training
   signal.
4. DECONTAMINATION. The first time the leakage check ran, it failed: at the
   original cap of 40 it flagged 102 of 5847 sentences (15 exact, 87 near); at
   the final cap of 20, 65 of 3629 (11 exact, 54 near). All but three were
   template renderings. They were removed without printing them or the
   questions: ``DECONTAMINATED`` lists a salted SHA-256
   prefix of each flagged sentence, produced by a script that printed only
   counts, family ids and digests, and re-run until the check was clean (70
   digests after four rounds, because each removal lets the family fill from
   renderings that may also be flagged). Expansion skips those sentences.
   Removing training sentences that resemble the test questions should make
   the external comparison harder for the model, not easier. Three families
   (trend-improving, shift-attainment, oee-overall) lost a free phrasing that
   way; each got one new free phrasing, written without knowing which one was
   removed, and the check was re-run clean. The list is exact for
   ``MAX_PER_FAMILY``: a different cap samples other renderings and must be
   re-checked (at 40 it would still flag 32).
5. SIZE. ``MAX_PER_FAMILY`` is 20 (the plan allows up to 40): at 40 the corpus
   was 5847 sentences, outside the planned 3-5k, and pure-Python full-batch
   training took about 0.5 s per epoch; at 20 it is about 3.6k (about 0.37 s per
   epoch). In a train/validation-only probe after 200 epochs, validation
   macro-F1 was 0.61 at cap 20 and 0.59 at cap 30 - indicative only, because
   the validation sentences change with the cap (the families do not).

Changing anything here changes ``corpus_sha256`` and therefore the artifact; a
changed corpus needs a rebuild, a new pin in classifier.py, and - for the
external sets, which are keyed by their own hash - it does NOT buy a fresh test.
"""
